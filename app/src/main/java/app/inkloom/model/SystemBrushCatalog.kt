        randomRotationDegrees: Float = 0f,
        strokeRotationJitterDegrees: Float = 0f,
        isEraser: Boolean = false,
        tags: List<String> = emptyList(),
    ) = ImportedBrush(
        id = id,
        name = name,
        format = BrushFormat.SYSTEM,
        compatibility = Compatibility.COMPLETE,
        sizeBytes = 0L,
        report = emptyList(),
        groupName = group,
        defaultSize = size,
        defaultOpacity = opacity,
